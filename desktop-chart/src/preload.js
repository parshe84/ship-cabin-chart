'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('ship', {
  onFix: (cb) => ipcRenderer.on('fix', (_e, fix) => cb(fix)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, s) => cb(s)),
  onDownloadProgress: (cb) => ipcRenderer.on('download-progress', (_e, p) => cb(p)),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (s) => ipcRenderer.invoke('save-settings', s),
  loadTrack: () => ipcRenderer.invoke('load-track'),
  saveTrack: (t) => ipcRenderer.invoke('save-track', t),
  loadWorldLayer: (name) => ipcRenderer.invoke('load-world-layer', name),
  loadLand: (name) => ipcRenderer.invoke('load-land', name),
  loadDepth: (name) => ipcRenderer.invoke('load-depth', name),
  exportGpx: (track) => ipcRenderer.invoke('export-gpx', track),
  exportRouteGpx: (waypoints) => ipcRenderer.invoke('export-route-gpx', waypoints),
  exportRouteRtz: (waypoints, name) => ipcRenderer.invoke('export-route-rtz', waypoints, name),
  importRoute: () => ipcRenderer.invoke('import-route'),
  encList: () => ipcRenderer.invoke('enc-list'),
  loadSeamarks: (name) => ipcRenderer.invoke('load-seamarks', name),
  encCatalogue: () => ipcRenderer.invoke('enc-catalogue'),
  encLoad: (name) => ipcRenderer.invoke('enc-load', name),
  encRemove: (names) => ipcRenderer.invoke('enc-remove', names),
  encImport: (kind) => ipcRenderer.invoke('enc-import', kind),
  onEncProgress: (cb) => ipcRenderer.on('enc-progress', (_e, p) => cb(p)),
  loadRoute: () => ipcRenderer.invoke('load-route'),
  saveRoute: (route) => ipcRenderer.invoke('save-route', route),
  downloadArea: (opts) => ipcRenderer.invoke('download-area', opts),
  downloadCorridor: (opts) => ipcRenderer.invoke('download-corridor', opts),
  onAis: (cb) => ipcRenderer.on('ais', (_e, msg) => cb(msg)),
  pairingQr: () => ipcRenderer.invoke('pairing-qr'),
  loadData: (name) => ipcRenderer.invoke('load-data', name),
  saveData: (name, value) => ipcRenderer.invoke('save-data', name, value),
  setFullscreen: (on) => ipcRenderer.invoke('set-fullscreen', on),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  downloadUpdate: () => ipcRenderer.invoke('download-update'),
  launchUpdate: (file) => ipcRenderer.invoke('launch-update', file),
  onUpdateProgress: (cb) => ipcRenderer.on('update-progress', (_e, p) => cb(p)),
});
